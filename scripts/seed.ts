async function runSeed() {
  console.log(`Seeding ${lessons.length} lessons...`);
  const chunkSize = 20;
  for (let i = 0; i < lessons.length; i += chunkSize) {
    const chunk = lessons.slice(i, i + chunkSize);
    const { error } = await supabase.from("lessons").insert(chunk);
    if (error) {
      console.error("Insert failed:", error.message);
      process.exit(1);
    }
  }
  console.log("Seed complete.");
}

runSeed().catch((error) => {
  console.error(error);
  process.exit(1);
});
